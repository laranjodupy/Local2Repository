const { withGradleProperties } = require('@expo/config-plugins');

/**
 * Raises the Gradle daemon's JVM heap/metaspace in android/gradle.properties.
 *
 * Why this exists: a `gradlew assembleRelease` build on this project (Expo
 * + NDK/CMake for 4 ABIs + Reanimated's native compile step) ran for over
 * an hour and then threw
 * `DaemonConnectionException: Could not dispatch a message to the daemon`
 * right after `BUILD SUCCESSFUL`. The build log itself explained why:
 *
 *   "Daemon will be stopped at the end of the build after running out of
 *   JVM Metaspace. ... currently configured max heap space is '2 GiB' and
 *   the configured max metaspace is '512 MiB'."
 *
 * The build still succeeded (the exception happens after the daemon's
 * work is done, while it's tearing down), but a starved daemon dies
 * instead of being reused, so every subsequent build pays full JVM
 * startup + whatever got re-evaluated cold — not something to leave
 * alone just because this one run happened to finish.
 *
 * android/gradle.properties is regenerated by `expo prebuild` (android/
 * is gitignored — docs/SPEC.md section 6 treats generated native folders
 * as disposable), so this can't be hand-edited there; it has to be a
 * config plugin that runs during prebuild. See
 * docs/decisions/ADR-003-gradle-daemon-memory.md.
 *
 * NOT YET VERIFIED: whether 4 GiB heap / 1 GiB metaspace is the right
 * number for this project specifically — chosen as a reasonable doubling
 * of Gradle's observed defaults (2 GiB / 512 MiB), not measured against
 * actual peak usage. If builds still die from Metaspace exhaustion,
 * raise further; if the build machine doesn't have 4 GiB free, lower it.
 */
const JVM_ARGS =
  '-Xmx4096m -XX:MaxMetaspaceSize=1024m -XX:+HeapDumpOnOutOfMemoryError';

module.exports = function withGradleJvmArgs(config) {
  return withGradleProperties(config, (config) => {
    const props = config.modResults;
    const existingIndex = props.findIndex(
      (item) => item.type === 'property' && item.key === 'org.gradle.jvmargs',
    );

    if (existingIndex === -1) {
      props.push({
        type: 'property',
        key: 'org.gradle.jvmargs',
        value: JVM_ARGS,
      });
    } else {
      props[existingIndex] = {
        type: 'property',
        key: 'org.gradle.jvmargs',
        value: JVM_ARGS,
      };
    }

    return config;
  });
};
